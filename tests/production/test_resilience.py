"""Production Resilience and Failover Test Suite.

Validates:
1. Groq HTTP 429 triggers failover to NVIDIA.
2. Groq and NVIDIA failures trigger failover to OpenAI.
3. Total provider outage returns a controlled error without mock fallback.
4. Response errors, timeouts, and HTTP 500 trigger fallback according to error policy.
5. Diagnostic logging records the provider used without leaking secrets.
6. HITL recovery persistence contract remains intact.
"""

from __future__ import annotations

import pytest

from albra_seed.core.config import SeedConfig
from albra_seed.core.base import LLMProvider
from albra_seed.core.identity import AgentIdentity
from albra_seed.core.types import (
    AgentResponse,
    ExecutionStatus,
    Message,
    Role,
    RunContext,
    Session,
)
from albra_seed.runtime import Agent, Runtime


class SimulatedProvider(LLMProvider):
    """Deterministic mock provider for testing resilience and failover."""

    def __init__(
        self,
        name: str,
        *,
        fail_mode: str | None = None,
        response_text: str | None = None,
        secret_leak: str | None = None,
    ) -> None:
        self.name = name
        self.fail_mode = fail_mode
        self.response_text = response_text or f"Response from {name}"
        self.secret_leak = secret_leak
        self.call_count = 0

    async def health(self) -> bool:
        return True

    async def complete(
        self,
        messages: list[Message],
        *,
        model: str | None = None,
        temperature: float = 0.2,
        max_tokens: int = 2048,
        tools: list[dict] | None = None,
        context: RunContext | None = None,
    ) -> AgentResponse:
        self.call_count += 1
        if self.fail_mode == "429":
            leak = f" [token={self.secret_leak}]" if self.secret_leak else ""
            raise RuntimeError(f"HTTP 429 Too Many Requests: Rate limit exceeded{leak}")
        if self.fail_mode == "500":
            raise RuntimeError("HTTP 500 Internal Server Error: Upstream service down")
        if self.fail_mode == "timeout":
            raise TimeoutError(f"Connection timeout after 30.0s to {self.name}")
        if self.fail_mode == "errors":
            return AgentResponse(
                content="",
                execution_id=context.execution_id if context else "exec-1",
                correlation_id=context.correlation_id if context else "corr-1",
                errors=[f"Upstream provider error from {self.name}: 503 Service Unavailable"],
            )
        if self.fail_mode == "invalid_json":
            return AgentResponse(
                content="",
                execution_id=context.execution_id if context else "exec-1",
                correlation_id=context.correlation_id if context else "corr-1",
                errors=["Malformed JSON response from LLM endpoint"],
            )

        return AgentResponse(
            content=self.response_text,
            execution_id=context.execution_id if context else "exec-1",
            correlation_id=context.correlation_id if context else "corr-1",
            metadata={"provider": self.name},
        )


def _build_test_agent(providers: list[SimulatedProvider]) -> tuple[Agent, Runtime]:
    cfg = SeedConfig()
    rt = Runtime(config=cfg)
    for p in providers:
        rt.register_provider(p)

    identity = AgentIdentity(
        name="resilience-test-agent",
        version="1.0.0",
        specialization="general",
        providers=[p.name for p in providers],
    )
    agent = Agent(identity=identity, runtime=rt)
    return agent, rt


# =====================================================================
# 1. Groq HTTP 429 -> NVIDIA Succeeds
# =====================================================================


@pytest.mark.asyncio
async def test_groq_429_failover_to_nvidia() -> None:
    """When Groq returns HTTP 429, execution transparently fails over to NVIDIA."""
    groq = SimulatedProvider("groq", fail_mode="429")
    nvidia = SimulatedProvider("nvidia", response_text="Answer generated by NVIDIA NIM")
    agent, _ = _build_test_agent([groq, nvidia])

    session = Session(agent_id=agent.identity.agent_id)
    ctx = RunContext(
        agent_id=agent.identity.agent_id,
        session_id=session.session_id,
        task="Test Groq 429 failover",
    )

    response = await agent.run("Hello resilience test", session=session, context=ctx)

    assert groq.call_count == 1
    assert nvidia.call_count == 1
    assert response.content == "Answer generated by NVIDIA NIM"
    assert "nvidia" in ctx.providers_used
    assert "groq" not in ctx.providers_used
    assert not response.errors
    assert ctx.status == ExecutionStatus.SUCCEEDED


