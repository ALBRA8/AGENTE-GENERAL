"""Secure provider settings store.

Persists provider configuration (base_url, model, temperature, top_p,
max_tokens, timeout, stream) and the encrypted API key to a local
SQLite database. The API key is encrypted with Fernet (authenticated
symmetric encryption) using a master key from ``SETTINGS_ENCRYPTION_KEY``.

SECURITY:
    - The API key is NEVER stored in plaintext.
    - The API key is NEVER returned by any read endpoint. ``get_config()``
      returns ``api_key_set: bool`` instead.
    - The master key MUST be provided via ``SETTINGS_ENCRYPTION_KEY``
      (a URL-safe base64-encoded 32-byte key, as generated by
      ``Fernet.generate_key()``). If the key is missing, the store
      fails closed: ``save_config()`` raises, ``save_api_key()`` raises,
      and ``get_api_key()`` returns None.
    - The store does NOT generate a random key at startup — that would
      make persisted keys unrecoverable after a restart.
    - The database file is created with mode 0600 on POSIX. The parent
      directory is created with mode 0700.

PERSISTENCE:
    - The SQLite database lives at ``ALBRA_PROVIDER_CONFIG_DB`` (default:
      ``./data/provider_config.db``). On Render, mount a persistent disk
      at ``./data/`` so the config survives redeploys.
    - The database schema is versioned (``PRAGMA user_version``).

ENVIRONMENT:
    - ``SETTINGS_ENCRYPTION_KEY`` — REQUIRED for any secret persistence.
      Generate with: ``python -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())"``
    - ``ALBRA_PROVIDER_CONFIG_DB`` — path to the SQLite database file.
      Default: ``./data/provider_config.db``.
"""

from __future__ import annotations

import base64
import hashlib
import json
import os
import sqlite3
import time
from pathlib import Path
from urllib.parse import urlsplit
from typing import Any

import structlog

log = structlog.get_logger("albra.config.settings")

_SCHEMA_VERSION = 1
_DEFAULT_DB_PATH = "./data/provider_config.db"


class SettingsEncryptionError(Exception):
    """Raised when encryption/decryption fails (e.g., missing key)."""


class ProviderConfigError(Exception):
    """Raised when provider config validation fails."""


def _validate_provider_base_url(base_url: str) -> None:
    """Restrict NVIDIA requests to the official HTTPS API endpoint.

    This provider currently supports NVIDIA's hosted API only. An exact
    host allowlist prevents a saved dashboard URL from turning the backend
    into an SSRF proxy for loopback, cloud metadata, or private services.
    """
    try:
        parsed = urlsplit(base_url)
        port = parsed.port
    except ValueError as exc:
        raise ProviderConfigError("Invalid NVIDIA base_url") from exc

    if (
        parsed.scheme != "https"
        or parsed.hostname != "integrate.api.nvidia.com"
        or parsed.username is not None
        or parsed.password is not None
        or port not in (None, 443)
        or parsed.path.rstrip("/") != "/v1"
        or parsed.query
        or parsed.fragment
    ):
        raise ProviderConfigError(
            "NVIDIA base_url must be https://integrate.api.nvidia.com/v1"
        )


def _get_master_key() -> bytes | None:
    """Read the Fernet master key from the environment.

    Returns None if ``SETTINGS_ENCRYPTION_KEY`` is not set (so callers
    can fail closed with a clear message).
    """
    raw = os.environ.get("SETTINGS_ENCRYPTION_KEY")
    if not raw:
        return None
    # The key must be a URL-safe base64-encoded 32-byte string.
    return raw.encode("utf-8")


def _get_fernet():
    """Build a Fernet cipher. Raises if cryptography is missing or key
    is not set.
    """
    key = _get_master_key()
    if key is None:
        raise SettingsEncryptionError(
            "SETTINGS_ENCRYPTION_KEY is not set. Generate one with: "
            'python -c "from cryptography.fernet import Fernet; '
            'print(Fernet.generate_key().decode())"'
        )
    try:
        from cryptography.fernet import Fernet
        return Fernet(key)
    except ImportError as exc:
        raise SettingsEncryptionError(
            "cryptography package is required for secure settings. "
            "Install with: pip install 'albra-seed[crypto]'"
        ) from exc
    except Exception as exc:
        raise SettingsEncryptionError(
            "Invalid SETTINGS_ENCRYPTION_KEY. The key must be a "
            "URL-safe base64-encoded 32-byte string (Fernet format)."
        ) from exc


def _encrypt(plaintext: str) -> str:
    """Encrypt a plaintext string. Returns a base64 token."""
    f = _get_fernet()
    return f.encrypt(plaintext.encode("utf-8")).decode("utf-8")


def _decrypt(token: str) -> str:
    """Decrypt a base64 token. Returns the plaintext string."""
    f = _get_fernet()
    return f.decrypt(token.encode("utf-8")).decode("utf-8")


def _db_path() -> Path:
    """Resolve the SQLite database path."""
    p = os.environ.get("ALBRA_PROVIDER_CONFIG_DB", _DEFAULT_DB_PATH)
    return Path(p)


def _ensure_db() -> sqlite3.Connection:
    """Open (or create) the settings database with correct permissions."""
    db_path = _db_path()
    db_path.parent.mkdir(parents=True, exist_ok=True)
    # Set parent dir to 0700 on POSIX (operator must verify pre-existing).
    try:
        if os.name == "posix":
            os.chmod(db_path.parent, 0o700)
    except OSError:
        pass  # best-effort

    # Reject symlinks BEFORE SQLite opens the path. Checking after
    # connect() is too late: SQLite may already have followed the link
    # and opened or created the target database.
    if db_path.is_symlink():
        raise ProviderConfigError(
            f"Provider config DB path must not be a symlink: {db_path}"
        )

    conn = sqlite3.connect(str(db_path))
    conn.row_factory = sqlite3.Row

    # Create schema if not exists.
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA user_version = 1")
    conn.execute("""
        CREATE TABLE IF NOT EXISTS provider_config (
            id INTEGER PRIMARY KEY CHECK (id = 1),
            provider TEXT NOT NULL,
            base_url TEXT NOT NULL,
            model TEXT NOT NULL,
            temperature REAL NOT NULL DEFAULT 0.5,
            top_p REAL NOT NULL DEFAULT 1.0,
            max_tokens INTEGER NOT NULL DEFAULT 1024,
            timeout REAL NOT NULL DEFAULT 60.0,
            stream INTEGER NOT NULL DEFAULT 0,
            api_key_encrypted TEXT,
            updated_at TEXT NOT NULL,
            last_test_at TEXT,
            last_test_ok INTEGER
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS schema_meta (
            key TEXT PRIMARY KEY,
            value TEXT NOT NULL
        )
    """)
    conn.commit()

    # Set file mode 0600 on POSIX.
    try:
        if os.name == "posix":
            os.chmod(db_path, 0o600)
    except OSError:
        pass

    return conn


