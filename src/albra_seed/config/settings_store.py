def get_config() -> dict[str, Any]:
    """Return the non-sensitive provider config.

    The API key is NOT included. Returns ``api_key_set: bool`` instead.
    If no config is saved, returns the default (Mock) config.
    """
    try:
        conn = _ensure_db()
        row = conn.execute(
            "SELECT * FROM provider_config WHERE id = 1"
        ).fetchone()
        conn.close()
    except Exception as exc:
        log.error("settings.db_error", error_type=type(exc).__name__)
        return {**DEFAULT_CONFIG, "api_key_set": False, "last_test_at": None,
                "last_test_ok": None}

    if row is None:
        return {**DEFAULT_CONFIG, "api_key_set": False, "last_test_at": None,
                "last_test_ok": None}

    return {
        "provider": row["provider"],
        "base_url": row["base_url"],
        "model": row["model"],
        "temperature": row["temperature"],
        "top_p": row["top_p"],
        "max_tokens": row["max_tokens"],
        "timeout": row["timeout"],
        "stream": bool(row["stream"]),
        "api_key_set": bool(row["api_key_encrypted"]),
        "last_test_at": row["last_test_at"],
        "last_test_ok": bool(row["last_test_ok"]) if row["last_test_ok"] is not None else None,
    }


def save_config(
    *,
    provider: str,
    base_url: str,
    model: str,
    temperature: float = 0.5,
    top_p: float = 1.0,
    max_tokens: int = 1024,
    timeout: float = 60.0,
    stream: bool = False,
) -> None:
    """Save the non-sensitive provider config (NOT the API key).

    If a previous config exists with an encrypted API key, the key is
    preserved — this method does NOT touch the ``api_key_encrypted``
    column.
    """
    if provider not in ("mock", "nvidia"):
        raise ProviderConfigError(
            f"Unknown provider: {provider!r}. Supported: mock, nvidia."
        )
    if provider == "nvidia" and not base_url:
        raise ProviderConfigError("base_url is required for nvidia provider")
    if provider == "nvidia" and not model:
        raise ProviderConfigError("model is required for nvidia provider")
    if not (0.0 <= temperature <= 2.0):
        raise ProviderConfigError("temperature must be between 0 and 2")
    if not (0.0 <= top_p <= 1.0):
        raise ProviderConfigError("top_p must be between 0 and 1")
    if max_tokens < 1 or max_tokens > 32768:
        raise ProviderConfigError("max_tokens must be between 1 and 32768")
    if timeout < 1 or timeout > 600:
        raise ProviderConfigError("timeout must be between 1 and 600 seconds")
    if provider == "nvidia":
        _validate_provider_base_url(base_url)

    conn = _ensure_db()
    now = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

    # Preserve the existing API key if one is set.
    existing = conn.execute(
        "SELECT api_key_encrypted FROM provider_config WHERE id = 1"
    ).fetchone()
    api_key_encrypted = existing["api_key_encrypted"] if existing else None

    conn.execute("""
        INSERT INTO provider_config (
            id, provider, base_url, model, temperature, top_p,
            max_tokens, timeout, stream, api_key_encrypted, updated_at
        ) VALUES (1, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(id) DO UPDATE SET
            provider = excluded.provider,
            base_url = excluded.base_url,
            model = excluded.model,
            temperature = excluded.temperature,
            top_p = excluded.top_p,
            max_tokens = excluded.max_tokens,
            timeout = excluded.timeout,
            stream = excluded.stream,
            api_key_encrypted = COALESCE(excluded.api_key_encrypted, provider_config.api_key_encrypted),
            updated_at = excluded.updated_at
    """, (
        provider, base_url, model, temperature, top_p,
        max_tokens, timeout, int(stream), api_key_encrypted, now,
    ))
    conn.commit()
    conn.close()
    log.info("settings.config_saved", provider=provider, model=model)


def save_api_key(api_key: str) -> None:
    """Encrypt and save the API key.

    Raises ``SettingsEncryptionError`` if ``SETTINGS_ENCRYPTION_KEY``
    is not set. The key is encrypted with Fernet before storage.
    """
    if not api_key:
        raise ProviderConfigError("api_key must not be empty")
    encrypted = _encrypt(api_key)
    conn = _ensure_db()
    now = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

    # Upsert: insert if not exists, update the api_key column only.
    existing = conn.execute(
        "SELECT id FROM provider_config WHERE id = 1"
    ).fetchone()
    if existing is None:
        # Insert a default config row so the key has somewhere to live.
        conn.execute("""
            INSERT INTO provider_config (
                id, provider, base_url, model, temperature, top_p,
                max_tokens, timeout, stream, api_key_encrypted, updated_at
            ) VALUES (1, 'mock', '', '', 0.5, 1.0, 1024, 60.0, 0, ?, ?)
        """, (encrypted, now))
    else:
        conn.execute("""
            UPDATE provider_config SET api_key_encrypted = ?, updated_at = ?
            WHERE id = 1
        """, (encrypted, now))
    conn.commit()
    conn.close()
    log.info("settings.api_key_saved")


def get_api_key() -> str | None:
    """Decrypt and return the API key. Returns None if not set or if
    decryption fails.

    SECURITY: This function is for INTERNAL USE ONLY — it must NEVER
    be exposed via an HTTP endpoint. The dashboard's "test connection"
    endpoint uses this to build the provider, but never returns the
    key to the caller.
    """
    try:
        conn = _ensure_db()
        row = conn.execute(
            "SELECT api_key_encrypted FROM provider_config WHERE id = 1"
        ).fetchone()
        conn.close()
    except Exception:
        return None

    if row is None or not row["api_key_encrypted"]:
        return None

    try:
        return _decrypt(row["api_key_encrypted"])
    except SettingsEncryptionError:
        return None
    except Exception as exc:
        log.error("settings.decrypt_failed", error_type=type(exc).__name__)
        return None


def clear_api_key() -> None:
    """Remove the API key from the store. The non-sensitive config is
    preserved.
    """
    conn = _ensure_db()
    conn.execute("""
        UPDATE provider_config SET api_key_encrypted = NULL WHERE id = 1
    """)
    conn.commit()
    conn.close()
    log.info("settings.api_key_cleared")


def record_test_result(ok: bool) -> None:
    """Record the result of the last connection test."""
    conn = _ensure_db()
    now = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

    # Check if a config row exists; if not, insert a default one first.
    existing = conn.execute(
        "SELECT id FROM provider_config WHERE id = 1"
    ).fetchone()
    if existing is None:
        conn.execute("""
            INSERT INTO provider_config (
                id, provider, base_url, model, temperature, top_p,
                max_tokens, timeout, stream, api_key_encrypted, updated_at,
                last_test_at, last_test_ok
            ) VALUES (1, 'mock', '', '', 0.5, 1.0, 1024, 60.0, 0, NULL, ?, ?, ?)
        """, (now, now, int(ok)))
    else:
        conn.execute("""
            UPDATE provider_config
            SET last_test_at = ?, last_test_ok = ?
            WHERE id = 1
        """, (now, int(ok)))
    conn.commit()
    conn.close()


def reset_to_defaults() -> None:
    """Reset the config to the Mock defaults. The API key is also cleared."""
    conn = _ensure_db()
    conn.execute("DELETE FROM provider_config WHERE id = 1")
    conn.execute("""
        INSERT INTO provider_config (
            id, provider, base_url, model, temperature, top_p,
            max_tokens, timeout, stream, api_key_encrypted, updated_at
        ) VALUES (1, 'mock', '', '', 0.5, 1.0, 1024, 60.0, 0, NULL, ?)
    """, (time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),))
    conn.commit()
    conn.close()
    log.info("settings.reset_to_defaults")


